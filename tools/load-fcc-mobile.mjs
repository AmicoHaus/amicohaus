// Hand-run loader: carrier-reported mobile coverage by ZIP code, San Diego County -> functions/_lib/fccMobileSd.js
// (the Signal Map's "carrier-reported coverage" lines, gate fccCoverage). Nothing here runs in a request, and nothing
// is downloaded: you download the files yourself and keep them OUTSIDE the repo.
//
// Inputs:
//   --fcc <folder>          the FCC National Broadband Map's California mobile-broadband downloads, one file per
//                           provider and technology, H3 hexagon version, as GeoPackage (.gpkg, an SQLite file).
//   --file <carrier>:<tech>=<file name>   which file is which (repeat it): carrier att, tmobile or verizon; tech 4g or
//                           5g (for 5G use the 5G-NR 7/1 Mbps file). Other providers are simply not listed.
//   --layer <table>         the table inside each file that holds the hexagons.          } not verified, so the loader
//   --h3-column <column>    the column that holds each hexagon's H3 index (resolution 9). } refuses to guess: use --inspect.
//   --zcta <file.geojson>   Census ZIP Code Tabulation Area outlines for San Diego County.
//   --zip-property <name>   the outline property that holds the 5-digit ZIP (default: ZCTA5CE20, ZCTA5CE10 or ZCTA5).
//   --h3 <folder>           a scratch folder where h3-js was installed ("npm i h3-js" there, never in this repo).
//   --as-of "June 2026"     the date of the FCC data, as the page will print it.
//   --out <path>            where to write the module (functions/_lib/fccMobileSd.js). Without it, nothing is written.
//   --hex-out <file.sql>    also write the hexagon-level table (cell centers) for a later batch. Never loaded in v1.
//   --inspect               list each file's tables and columns (and the outline file's properties), then stop.
//
// Steps: (1) for each ZIP outline, the resolution-9 cells whose center is inside it; (2) for each carrier and
// technology, how many of the ZIP's cells are in that carrier's file; (3) a bucket: no cells = 0 (not reported),
// under 50% = 1 (in parts of the ZIP), 50% to under 99% = 2 (in most of it), 99% or more = 3 (across it);
// (4) the module; (5) a table to read before the fccCoverage gate is turned on (functions/_lib/nuancedGate.js).
// The FCC's mobile coverage is outdoor or in-vehicle coverage as carriers report it, not indoor and not a test.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';

export const CARRIER_KEYS = ['att', 'tmobile', 'verizon'];
export const TECH_KEYS = ['4g', '5g'];
export const H3_RESOLUTION = 9;
export const NEEDS_LAYER_ERROR = 'Give --layer and --h3-column (run with --inspect to see what the files hold). The loader does not guess them.';

// 0 not reported, 1 in parts of the ZIP, 2 in most of it, 3 across it.
export function coverageBucket(covered, total) {
  if (!(total > 0) || !(covered > 0)) return 0;
  const share = covered / total;
  return share >= 0.99 ? 3 : share >= 0.5 ? 2 : 1;
}

// zipCells: Map(zip -> Set(cell)); carrierCells: { att: { '4g': Set, '5g': Set }, ... } (a missing file = not reported).
// -> { zip: { att: [4G, 5G], tmobile: [...], verizon: [...] } }, only for carriers that were given at least one file.
export function buildCoverage(zipCells, carrierCells) {
  const zips = {};
  for (const [zip, cells] of [...zipCells].sort(([a], [b]) => (a < b ? -1 : 1))) {
    if (!cells.size) continue;
    const row = {};
    for (const carrier of CARRIER_KEYS) {
      const files = carrierCells[carrier];
      if (!files) continue;
      row[carrier] = TECH_KEYS.map((tech) => {
        const set = files[tech];
        if (!set) return 0;
        let covered = 0;
        for (const c of cells) if (set.has(c)) covered++;
        return coverageBucket(covered, cells.size);
      });
    }
    if (Object.keys(row).length) zips[zip] = row;
  }
  return zips;
}

export function fccModuleText({ asOf, zips }) {
  const rows = Object.keys(zips).sort().map(z => `  '${z}': ${JSON.stringify(zips[z])},`).join('\n');
  return `// GENERATED by tools/load-fcc-mobile.mjs (run by hand): carrier-reported mobile coverage by ZIP code, San Diego County.
// Source: FCC National Broadband Map (Broadband Data Collection). For each ZIP: carrier -> [4G, 5G], each 0-3
// (0 not reported, 1 in parts of the ZIP, 2 in most of it, 3 across it).
export const FCC_MOBILE = { asOf: ${JSON.stringify(asOf)}, zips: {
${rows}
} };
`;
}

// The command line: --name value pairs; --file may repeat; --inspect is a flag.
export function parseArgs(argv) {
  const out = { files: [] };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (!a.startsWith('--')) continue;
    const key = a.slice(2);
    const value = argv[i + 1] !== undefined && !argv[i + 1].startsWith('--') ? argv[++i] : true;
    if (key === 'file') out.files.push(value); else out[key] = value;
  }
  return out;
}

// "att:5g=some file.gpkg" -> { carrier, tech, name }.
export function parseFileArg(text) {
  const m = /^(att|tmobile|verizon):(4g|5g)=(.+)$/i.exec(String(text || ''));
  if (!m) throw new Error(`--file should look like att:4g=<file name> (carriers: ${CARRIER_KEYS.join(', ')}; technologies: ${TECH_KEYS.join(', ')}). Got: ${text}`);
  return { carrier: m[1].toLowerCase(), tech: m[2].toLowerCase(), name: m[3] };
}

const IDENT = /^[A-Za-z0-9_]+$/;
// An H3 index as the lowercase hex text h3-js uses (a file may store it as text or as a whole number).
function cellKey(v) {
  if (typeof v === 'bigint') return v.toString(16);
  if (typeof v === 'number') return BigInt(v).toString(16);
  return String(v || '').trim().toLowerCase();
}

// Each ZIP outline -> the resolution-9 cells whose center is inside it. h3 = the h3-js module.
export function zipCellsFromOutlines(geojson, h3, zipProperty) {
  const out = new Map();
  for (const feature of (geojson && geojson.features) || []) {
    const zip = String((feature.properties || {})[zipProperty] || '').trim();
    const geom = feature.geometry || {};
    if (!/^\d{5}$/.test(zip)) continue;
    const polygons = geom.type === 'Polygon' ? [geom.coordinates] : geom.type === 'MultiPolygon' ? geom.coordinates : [];
    const cells = out.get(zip) || new Set();
    for (const rings of polygons) for (const c of h3.polygonToCells(rings, H3_RESOLUTION, true)) cells.add(cellKey(c));
    out.set(zip, cells);
  }
  return out;
}

async function openSqlite(file) {
  const { DatabaseSync } = await import('node:sqlite');
  return new DatabaseSync(file, { readOnly: true });
}

async function inspect(a) {
  if (a.fcc && a.fcc !== true) {
    for (const name of fs.readdirSync(a.fcc).filter(n => /\.(gpkg|sqlite|db)$/i.test(n)).sort()) {
      console.log(`\n${name}`);
      try {
        const db = await openSqlite(path.join(a.fcc, name));
        for (const t of db.prepare("SELECT name FROM sqlite_master WHERE type IN ('table', 'view') ORDER BY name").all()) {
          if (!IDENT.test(t.name)) { console.log(`  ${t.name}`); continue; }
          const cols = db.prepare(`PRAGMA table_info("${t.name}")`).all().map(c => `${c.name} ${c.type}`.trim());
          console.log(`  ${t.name}: ${cols.join(', ')}`);
        }
        db.close();
      } catch (e) { console.log(`  could not be opened as SQLite: ${e.message}`); }
    }
  }
  if (a.zcta && a.zcta !== true) {
    const geo = JSON.parse(fs.readFileSync(a.zcta, 'utf8'));
    const first = (geo.features || [])[0] || {};
    console.log(`\n${path.basename(a.zcta)}: ${(geo.features || []).length} outlines; properties: ${Object.keys(first.properties || {}).join(', ')}`);
  }
}

async function main() {
  const a = parseArgs(process.argv.slice(2));
  if (a.inspect) { await inspect(a); return; }
  const stop = (message) => { console.error(`Stopped: ${message}`); process.exit(1); };
  if (!a.layer || a.layer === true || !a['h3-column'] || a['h3-column'] === true) stop(NEEDS_LAYER_ERROR);
  if (!IDENT.test(a.layer) || !IDENT.test(a['h3-column'])) stop('--layer and --h3-column should be plain names (letters, digits, underscores).');
  for (const need of ['fcc', 'zcta', 'h3', 'as-of']) if (!a[need] || a[need] === true) stop(`Give --${need}.`);
  if (!a.files.length) stop('Say which file is which with --file <carrier>:<tech>=<file name> (for example --file att:4g=att_4g_h3.gpkg). The loader does not guess from file names.');
  let files;
  try { files = a.files.map(parseFileArg); } catch (e) { stop(e.message); }

  // h3-js lives in a scratch folder, never in this repo.
  let h3;
  try { h3 = createRequire(path.join(path.resolve(a.h3), 'noop.js'))('h3-js'); } catch (e) { stop(`h3-js was not found in ${a.h3} (run "npm i h3-js" in that folder): ${e.message}`); }

  const geo = JSON.parse(fs.readFileSync(a.zcta, 'utf8'));
  const props = Object.keys((((geo.features || [])[0] || {}).properties) || {});
  const zipProperty = a['zip-property'] && a['zip-property'] !== true ? a['zip-property'] : ['ZCTA5CE20', 'ZCTA5CE10', 'ZCTA5'].find(p => props.includes(p));
  if (!zipProperty) stop(`Give --zip-property (the outline property that holds the ZIP). Properties: ${props.join(', ')}`);
  const zipCells = zipCellsFromOutlines(geo, h3, zipProperty);
  if (!zipCells.size) stop('No ZIP outlines were read.');
  const county = new Set();
  for (const cells of zipCells.values()) for (const c of cells) county.add(c);
  console.log(`${zipCells.size} ZIP outlines, ${county.size} resolution-${H3_RESOLUTION} cells.`);

  // Only cells inside the county's ZIP outlines are kept from each carrier file.
  const carrierCells = {};
  for (const f of files) {
    const db = await openSqlite(path.join(a.fcc, f.name));
    const set = new Set();
    for (const row of db.prepare(`SELECT "${a['h3-column']}" AS cell FROM "${a.layer}"`).iterate()) {
      const key = cellKey(row.cell);
      if (county.has(key)) set.add(key);
    }
    db.close();
    carrierCells[f.carrier] = carrierCells[f.carrier] || {};
    const had = carrierCells[f.carrier][f.tech];
    if (had) for (const c of set) had.add(c); else carrierCells[f.carrier][f.tech] = set;
    console.log(`${f.carrier} ${f.tech}: ${set.size} cells in the county (${f.name})`);
  }

  const zips = buildCoverage(zipCells, carrierCells);
  const WORDS = ['not reported', 'parts', 'most', 'across'];
  console.log(`\nData as of ${a['as-of']}\nZIP     cells  ${CARRIER_KEYS.map(c => `${c} 4G / 5G`.padEnd(22)).join('')}`);
  for (const zip of Object.keys(zips).sort()) {
    console.log(`${zip}  ${String(zipCells.get(zip).size).padStart(6)}  ${CARRIER_KEYS.map(c => (zips[zip][c] ? `${WORDS[zips[zip][c][0]]} / ${WORDS[zips[zip][c][1]]}` : '-').padEnd(22)).join('')}`);
  }

  const text = fccModuleText({ asOf: String(a['as-of']), zips });
  if (a.out && a.out !== true) { fs.writeFileSync(a.out, text); console.log(`\nWrote ${a.out}. Read the table above before turning the fccCoverage gate on.`); }
  else console.log('\n(no --out given: nothing written)');

  // The hexagon-level table for a later batch (a private map spot): cell centers and one bit per carrier and technology.
  if (a['hex-out'] && a['hex-out'] !== true) {
    const bitOf = (carrier, tech) => 1 << (CARRIER_KEYS.indexOf(carrier) * 2 + TECH_KEYS.indexOf(tech));
    const lines = ['CREATE TABLE IF NOT EXISTS fcc_mobile_hex (lat REAL, lng REAL, bits INTEGER);'];
    let count = 0;
    for (const cell of county) {
      let bits = 0;
      for (const carrier of CARRIER_KEYS) for (const tech of TECH_KEYS) if (carrierCells[carrier] && carrierCells[carrier][tech] && carrierCells[carrier][tech].has(cell)) bits |= bitOf(carrier, tech);
      const [lat, lng] = h3.cellToLatLng(cell);
      lines.push(`INSERT INTO fcc_mobile_hex (lat, lng, bits) VALUES (${Number(lat).toFixed(5)}, ${Number(lng).toFixed(5)}, ${bits});`);
      count++;
    }
    fs.writeFileSync(a['hex-out'], lines.join('\n') + '\n');
    console.log(`Wrote ${count} cell centers to ${a['hex-out']} (not loaded anywhere in this version).`);
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await main();
